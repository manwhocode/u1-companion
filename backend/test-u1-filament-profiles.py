"""Isolated file/dispatch tests; never connect to a printer or heat hardware."""
import copy
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
from u1_filament_profiles import PrintPlan, U1FilamentProfiles

PREFIX = b'''; generated by Snapmaker Orca 2.3.5 on test
PRINT_START
M140 S65
M104 T0 S140
T0
M109 T0 S130
M109 S170
M104 S130
M109 S130
M190 S65
G28 Z
M109 S220
G1 Z0.2
G1 X185 E15 F360
;LAYER_CHANGE
M104 T0 S220
G1 X20 E1
PRINT_END
M104 S0 T0 A0
M140 S0
'''
FOOTER = b'''; filament used [g] = 10,0,0,0
; nozzle_temperature = 220,220,220,220
; nozzle_temperature_initial_layer = 220,220,220,220
; curr_bed_type = Textured PEI Plate
; textured_plate_temp = 65,65,65,65
; textured_plate_temp_initial_layer = 65,65,65,65
; first_layer_bed_temperature = 65
'''


def data():
    return {'library': {'entries': [{'id': 'c', 'material': 'PLA', 'hex': '#000000', 'nozzleTemperature': 235, 'bedTemperature': 60,
                                    'calibration': {'pressureAdvance': .024}}]},
            'inventory': {'heads': ['s', None, None, None], 'spools': [{'id': 's', 'colorId': 'c', 'material': 'PLA', 'hex': '#000000'}]}}


def task():
    return {'extruder_map_table': list(range(4)), 'filament_type': ['PLA'] * 4, 'filament_color_rgba': ['000000FF'] * 4,
            'flow_calibrate': False, 'flow_calib_extruders': [True] * 4}


class ProfileTests(unittest.TestCase):
    def setUp(self):
        root = Path(__file__).resolve().parent / 'local-backups' / 'profile-tests'
        root.mkdir(parents=True, exist_ok=True)
        self.tmp = tempfile.TemporaryDirectory(dir=root)
        self.addCleanup(self.tmp.cleanup)
        self.path = Path(self.tmp.name) / 'print.gcode'
        self.path.write_bytes(PREFIX + FOOTER)
        self.data, self.task = data(), task()

    def plan(self):
        return PrintPlan(self.data, self.task, self.path)

    def transformed(self, plan):
        position, output = 0, []
        for raw in self.path.read_bytes().splitlines(keepends=True):
            line = raw.decode().rstrip('\r\n')
            output.append(plan.rewrite(line, position, self.task, 0))
            position += len(raw)
        return output

    def test_only_print_heat_and_bed_changed_original_file_untouched(self):
        before = self.path.read_bytes()
        result = self.transformed(self.plan())
        for line in ['M104 T0 S140', 'M109 T0 S130', 'M109 S170', 'M104 S130', 'M109 S130', 'M104 S0 T0 A0', 'M140 S0']:
            self.assertIn(line, result)
        for line in ['M109 S235', 'M104 T0 S235', 'M140 S60', 'M190 S60']:
            self.assertIn(line, result)
        self.assertEqual(self.path.read_bytes(), before)

    def test_inheritance_uses_current_color_not_spool_copy(self):
        self.data['library']['entries'][0]['nozzleTemperature'] = 245
        self.assertIn('M109 S245', self.transformed(self.plan()))
        self.assertNotIn('nozzleTemperature', self.data['inventory']['spools'][0])

    def test_spool_override_each_field_and_reset_to_updated_base(self):
        spool = self.data['inventory']['spools'][0]
        spool['nozzleTemperature'] = 250
        resolved = self.plan().resolve(self.task)[0]
        self.assertEqual(resolved['nozzleTemperature'], 250)
        self.assertEqual(resolved['bedTemperature'], 60)
        self.data['library']['entries'][0].update(nozzleTemperature=240, bedTemperature=65)
        self.assertEqual(self.plan().resolve(self.task)[0]['nozzleTemperature'], 250)
        self.assertEqual(self.plan().resolve(self.task)[0]['bedTemperature'], 65)
        spool['bedTemperature'] = 70
        self.assertEqual(self.plan().resolve(self.task)[0]['bedTemperature'], 70)
        del spool['nozzleTemperature']
        del spool['bedTemperature']
        self.assertIn('M109 S240', self.transformed(self.plan()))
        self.assertEqual(self.plan().resolve(self.task)[0]['bedTemperature'], 65)

    def test_own_temperature_without_color_temperatures_and_independent_of_k_mode(self):
        self.data['library']['entries'][0] = {'id': 'c', 'material': 'PLA', 'hex': '#000000'}
        self.data['inventory']['spools'][0]['nozzleTemperature'] = 245
        for individual in (False, True):
            self.data['inventory']['individualCalibration'] = individual
            self.assertIn('M109 S245', self.transformed(self.plan()))

    def test_spool_temperature_limits_and_shared_bed_conflict(self):
        self.data['inventory']['spools'][0]['nozzleTemperature'] = 301
        with self.assertRaises(ValueError): self.plan()
        self.data = data()
        self.path.write_bytes(PREFIX + FOOTER.replace(b'10,0,0,0', b'10,10,0,0'))
        self.data['inventory']['spools'].append({'id': 's2', 'colorId': 'c', 'material': 'PLA', 'hex': '#000000', 'bedTemperature': 80})
        self.data['inventory']['heads'][1] = 's2'
        with self.assertRaisesRegex(ValueError, 'разные температуры'): self.plan()

    def test_empty_settings_leave_slicer_untouched(self):
        for key in ['nozzleTemperature', 'bedTemperature', 'calibration']:
            del self.data['library']['entries'][0][key]
        plan = self.plan()
        self.assertFalse(plan.enabled)
        self.assertEqual(self.transformed(plan), self.path.read_text().splitlines())

    def test_frozen_snapshot_does_not_change_mid_print(self):
        plan = self.plan()
        self.data['library']['entries'][0]['nozzleTemperature'] = 270
        self.assertIn('M109 S235', self.transformed(plan))

    def test_unassigned_library_profiles_do_not_restrict_stock_files(self):
        self.data['inventory']['heads'] = [None] * 4
        self.path.write_text('G28\n')
        self.assertFalse(self.plan().enabled)

    def test_logical_to_physical_and_direct_address(self):
        self.task['extruder_map_table'] = [2, 1, 0, 3]
        self.data['inventory']['heads'] = [None, None, 's', None]
        plan = self.plan()
        plan.printing = True
        self.assertEqual(plan.rewrite('M109 T0 S220 ; test', 999, self.task, 0), 'M109 T0 S235 ; test')
        self.assertEqual(plan.rewrite('M104 T2 S220 A0', 999, self.task, 0), 'M104 T2 S235 A0')
        self.assertEqual(plan.rewrite('M104 T0 S220 A0', 999, self.task, 0), 'M104 T0 S220 A0')

    def test_standby_and_heater_off_never_raised(self):
        plan = self.plan()
        plan.printing = True
        for line in ['M104 T0 S140', 'M104 T0 S0', 'M109 T0 S-1', 'M140 S0', '; M109 S220']:
            self.assertEqual(plan.rewrite(line, 999, self.task, 0), line)

    def test_common_and_individual_k_zero(self):
        plan = self.plan()
        self.assertEqual(plan.k_values(self.task, {0: .02}), {0: .024})
        self.data['inventory']['individualCalibration'] = True
        self.data['inventory']['spools'][0]['calibration'] = {'pressureAdvance': 0}
        self.assertEqual(self.plan().k_values(self.task, {0: .02}), {0: 0})
        del self.data['inventory']['spools'][0]['calibration']
        self.assertEqual(self.plan().k_values(self.task, {0: .02}), {})

    def test_fresh_native_calibration_has_priority_over_saved_and_slicer(self):
        self.task['flow_calibrate'] = True
        plan = self.plan()
        plan.printing = True
        self.assertEqual(plan.k_values(self.task, {0: .031}), {})
        self.assertEqual(plan.rewrite('SET_PRESSURE_ADVANCE ADVANCE=0.08', 999, self.task, 0), 'SET_PRESSURE_ADVANCE ADVANCE=0.031')

    def test_slicer_pa_cannot_overwrite_saved_k(self):
        plan = self.plan()
        plan.printing = True
        self.assertEqual(plan.rewrite('SET_PRESSURE_ADVANCE EXTRUDER=extruder ADVANCE=0.04 SMOOTH_TIME=0.04', 999, self.task, 0),
                         'SET_PRESSURE_ADVANCE EXTRUDER=extruder ADVANCE=0.024 SMOOTH_TIME=0.04')
        self.assertEqual(plan.rewrite('SET_PRESSURE_ADVANCE EXTRUDER=extruder1 ADVANCE=0.04', 999, self.task, 0),
                         'SET_PRESSURE_ADVANCE EXTRUDER=extruder1 ADVANCE=0.04')

    def test_wrong_material_or_color_blocks_before_heating(self):
        self.task['filament_type'][0] = 'PETG'
        with self.assertRaises(ValueError): self.plan()

    def test_conflicting_shared_bed_blocks_before_heating(self):
        self.path.write_bytes(PREFIX + FOOTER.replace(b'10,0,0,0', b'10,10,0,0'))
        self.data['library']['entries'].append({'id': 'c2', 'material': 'PLA', 'hex': '#000000', 'bedTemperature': 80})
        self.data['inventory']['spools'].append({'id': 's2', 'colorId': 'c2', 'material': 'PLA', 'hex': '#000000'})
        self.data['inventory']['heads'][1] = 's2'
        with self.assertRaisesRegex(ValueError, 'разные температуры'): self.plan()

    def test_limits_invalid_values_and_unknown_file(self):
        for value in (True, -1, 0, 1000, float('nan')):
            self.data['library']['entries'][0]['nozzleTemperature'] = value
            with self.assertRaises(ValueError): self.plan()
        self.data = data()
        with self.assertRaises(ValueError): PrintPlan(self.data, self.task, self.path, nozzle_max=230)
        self.path.write_bytes(PREFIX.replace(b'Snapmaker Orca', b'unknown slicer') + FOOTER)
        with self.assertRaises(ValueError): self.plan()

    def test_cleanup_equal_to_metadata_is_still_preserved(self):
        self.path.write_bytes(PREFIX.replace(b'M109 S170', b'M109 S220') + FOOTER)
        result = self.transformed(self.plan())
        self.assertIn('M109 S220', result)
        self.assertEqual(result.count('M109 S235'), 1)

    def test_after_print_end_no_changes(self):
        plan = self.plan()
        plan.printing = True
        plan.rewrite('PRINT_END', 999, self.task, 0)
        self.assertEqual(plan.rewrite('M109 S220', 1000, self.task, 0), 'M109 S220')

    def test_no_safe_print_wait_blocks(self):
        self.path.write_bytes(PREFIX.replace(b'M109 S220\n', b'') + FOOTER)
        with self.assertRaises(ValueError): self.plan()

    def test_utf8_crlf_offsets(self):
        self.path.write_bytes((b'; generated by Snapmaker Orca 2.3.5 on test\n' + '; Тест\n'.encode() + PREFIX.split(b'\n', 1)[1] + FOOTER).replace(b'\n', b'\r\n'))
        plan = self.plan()
        self.assertEqual(self.path.read_bytes()[plan.prime_offset:][:11], b'M109 S220\r\n')
        self.assertIn('M109 S235', self.transformed(plan))


class DispatchTests(unittest.TestCase):
    setUp = ProfileTests.setUp
    def attach(self, recovered=False):
        from types import SimpleNamespace
        outer = self
        self.resumes, self.original_lines, self.scripts = 0, 0, []
        self.ks = {i: .02 for i in range(4)}
        self.mirror = Path(self.tmp.name) / 'current.json'
        self.mirror.write_text(json.dumps({'format': 'u1-filament-data', 'version': 1, 'data': self.data}))
        def resume(): outer.resumes += 1
        def process(line):
            outer.original_lines += 1
            return line
        vsd = SimpleNamespace(current_file=SimpleNamespace(name=str(self.path)), work_timer=None,
                              file_position=100 if recovered else 0, do_resume=resume, process_gcode_line=process)
        def execute(script):
            outer.scripts.append(script)
            import re
            match = re.search(r'EXTRUDER=extruder([123]?) ADVANCE=([0-9.]+)', script)
            outer.ks[int(match.group(1) or 0)] = float(match.group(2))
        objects = {'virtual_sdcard': vsd, 'gcode': SimpleNamespace(run_script_from_command=execute, respond_info=lambda message: None),
                   'print_task_config': SimpleNamespace(get_status=lambda: copy.deepcopy(outer.task)),
                   'toolhead': SimpleNamespace(get_extruder=lambda: SimpleNamespace(get_name=lambda: 'extruder')),
                   'configfile': SimpleNamespace(get_status=lambda event: {'settings': {**{name: {'max_temp': 300} for name in ['extruder', 'extruder1', 'extruder2', 'extruder3']}, 'heater_bed': {'max_temp': 100}}})}
        for i in range(4):
            objects['extruder' if i == 0 else 'extruder%d' % i] = SimpleNamespace(get_status=lambda event, head=i: {'pressure_advance': outer.ks[head]})
        printer = SimpleNamespace(lookup_object=lambda name: objects[name], command_error=ValueError, register_event_handler=lambda event, callback: None)
        config = SimpleNamespace(get_printer=lambda: printer, get=lambda key, default: str(outer.mirror))
        module = U1FilamentProfiles(config)
        module.connect()
        return module, vsd

    def test_dispatch_preserves_native_hook_and_applies_k_only_at_print_heat(self):
        module, vsd = self.attach()
        vsd.do_resume()
        self.assertEqual(self.scripts, [])
        position = 0
        for raw in self.path.read_bytes().splitlines(keepends=True):
            vsd.file_position = position
            line = raw.decode().strip()
            result = vsd.process_gcode_line(line)
            if position < module.plan.prime_offset:
                self.assertEqual(self.scripts, [])
            if position == module.plan.prime_offset:
                self.assertEqual(result, 'M109 S235')
                self.assertEqual(self.ks[0], .024)
            position += len(raw)
        self.assertEqual(self.original_lines, len(self.path.read_bytes().splitlines()))
        self.assertEqual(module.get_status()['state'], 'finished')
        self.assertEqual(len(self.scripts), 1)

    def test_paused_resume_uses_frozen_profile(self):
        module, vsd = self.attach()
        vsd.do_resume()
        plan = module.plan
        vsd.file_position = 100
        self.mirror.write_text('{}')
        vsd.do_resume()
        self.assertIs(module.plan, plan)
        self.assertEqual(self.resumes, 2)

    def test_power_loss_restore_without_plan_does_not_override_stock(self):
        module, vsd = self.attach(True)
        vsd.do_resume()
        self.assertEqual(module.get_status()['state'], 'stock-recovery')
        self.assertEqual(vsd.process_gcode_line('M109 S220'), 'M109 S220')
        self.assertEqual(self.scripts, [])

    def test_global_native_calibration_blocks_all_saved_k_as_stock_requires(self):
        self.task['flow_calibrate'] = True
        self.task['flow_calib_extruders'] = [False] * 4
        module, vsd = self.attach()
        vsd.do_resume()
        vsd.file_position = module.plan.prime_offset
        self.ks[0] = .019
        self.assertEqual(vsd.process_gcode_line('M109 S220'), 'M109 S235')
        self.assertEqual(self.scripts, [])
        self.assertEqual(self.ks[0], .019)

    def test_transaction_in_progress_blocks_start_without_side_effects(self):
        module, vsd = self.attach()
        (Path(self.tmp.name) / 'transaction.json').write_text('{}')
        with self.assertRaises(ValueError): vsd.do_resume()
        self.assertEqual(self.resumes, 0)
        self.assertEqual(self.scripts, [])


if __name__ == '__main__': unittest.main()
