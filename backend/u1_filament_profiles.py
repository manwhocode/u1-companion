"""Additive U1 print-file profiles. Stock files and manual heater commands are unchanged.

Only known Orca print temperatures are substituted in virtual-SD file commands.
The original file, byte offsets, cleanup temperatures and heater-off commands stay intact.
"""
import copy
import json
import math
import os
import re

NUMBER = r'[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?'
BED_KEYS = {'Textured PEI Plate': 'textured_plate_temp', 'Smooth PEI Plate': 'hot_plate_temp',
            'High Temp Plate': 'hot_plate_temp', 'Engineering Plate': 'eng_plate_temp',
            'Cool Plate': 'cool_plate_temp', 'Graphic Effect Plate': 'textured_plate_temp',
            'Textured Cool Plate': 'textured_cool_plate_temp', 'Supertack Plate': 'supertack_plate_temp'}


def numeric(value, low, high):
    if type(value) not in (int, float) or not math.isfinite(value) or not low <= value <= high:
        raise ValueError('Некорректная температура или K в библиотеке.')
    return value


def command(line):
    return line.split(';', 1)[0].strip()


def parameter(line, key, default=None):
    matches = re.findall(r'(?:^|\s)' + re.escape(key) + r'\s*(' + NUMBER + r')(?=\s|$)', command(line), re.I)
    if len(matches) > 1:
        raise ValueError('Повторяющийся параметр ' + key)
    return float(matches[0]) if matches else default


def replace_number(line, key, value, extended=False):
    separator = '=' if extended else r'\s*'
    pattern = r'(?i)(?<!\S)(' + re.escape(key) + separator + r')' + NUMBER + r'(?=\s|$)'
    body, sep, comment = line.partition(';')
    body, count = re.subn(pattern, lambda match: match.group(1) + format(value, '.9g'), body)
    if count != 1:
        raise ValueError('Неподдерживаемый формат параметра ' + key)
    return body + sep + comment


def vector(metadata, key):
    raw = metadata.get(key)
    if raw is None:
        raise ValueError('В G-code отсутствует поле ' + key)
    values = [float(value.strip()) for value in re.split(r'[,;]', raw)]
    if not values or any(not math.isfinite(value) for value in values):
        raise ValueError('Неверный профиль слайсера: ' + key)
    return values


class PrintPlan:
    def __init__(self, data, task, path, nozzle_max=300, bed_max=100):
        self.data = copy.deepcopy(data)
        self.nozzle_max, self.bed_max = nozzle_max, bed_max
        self.printing = False
        self.ended = False
        self.fresh_k = {}
        self.prime_offset = None
        self.metadata = {}
        self.used = []
        self.enabled = False
        self.bed_baseline = set()
        # Unconfigured libraries must not impose any new G-code requirements.
        colors = {color['id']: color for color in data['library']['entries']}
        assigned = set(data['inventory']['heads']) - {None}
        self.potential = False
        for spool in data['inventory']['spools']:
            if spool['id'] not in assigned:
                continue
            color = colors.get(spool['colorId'], {})
            calibration = spool.get('calibration', {}) if data['inventory'].get('individualCalibration') else color.get('calibration', {})
            self.potential |= any(key in color or key in spool for key in ('nozzleTemperature', 'bedTemperature')) or 'pressureAdvance' in calibration
        if not self.potential:
            return
        with open(path, 'rb') as source:
            prefix = source.read(512 * 1024)
            source.seek(max(0, os.fstat(source.fileno()).st_size - 256 * 1024))
            footer = source.read().decode('utf-8', errors='replace')
        for line in footer.splitlines():
            match = re.fullmatch(r';\s*([^=]+?)\s*=\s*(.*?)\s*', line)
            if match:
                self.metadata[match.group(1).strip()] = match.group(2)
        weights = vector(self.metadata, 'filament used [g]')
        self.used = [index for index, weight in enumerate(weights) if weight > 0]
        if not self.used:
            raise ValueError('Не удалось определить используемые филаменты в G-code.')
        self.nozzle = vector(self.metadata, 'nozzle_temperature')
        self.initial = vector(self.metadata, 'nozzle_temperature_initial_layer')
        self.mapping(task)
        resolved = self.resolve(task)
        self.enabled = any(profile for profile in resolved.values())
        if not self.enabled:
            return
        if not re.search(rb'; generated by (?:Snapmaker Orca|OrcaSlicer) ', prefix[:4096]):
            raise ValueError('Профили поддерживают G-code Snapmaker Orca/OrcaSlicer с сохранёнными настройками. Исходный файл не изменён.')
        # Identify the last print-temperature wait before the first explicit purge.
        # Cleaning waits are never selected just because they have the same S value.
        position, candidate, first_extrusion = 0, None, False
        candidate_line, scan_active = '', self.mapping(task)[self.used[0]]
        for raw in prefix.splitlines(keepends=True):
            line = raw.decode('utf-8', errors='strict').rstrip('\r\n')
            body = command(line)
            tool = re.match(r'^T(\d+)(?:\s|$)', body, re.I)
            if tool:
                scan_active = self.physical(int(tool.group(1)), task, parameter(line, 'A', 1) == 0)
            if re.match(r'^M109(?:\s|$)', body, re.I):
                candidate = position
                candidate_line = line
                specified = parameter(line, 'T')
                candidate_head = scan_active if specified is None else self.physical(int(specified), task, parameter(line, 'A', 1) == 0)
            if re.match(r'^G[01](?:\s|$)', body, re.I) and (parameter(line, 'E', 0) or 0) > 0:
                first_extrusion = True
                self.prime_offset = candidate
                break
            if line.strip() == ';LAYER_CHANGE':
                break
            position += len(raw)
        if not first_extrusion or self.prime_offset is None:
            raise ValueError('Не удалось безопасно определить окончание очистки и начало печати. Нагрев не запущен.')
        expected = {values[index] for index in self.used if self.mapping(task)[index] == candidate_head for values in (self.nozzle, self.initial)}
        if parameter(candidate_line, 'S') not in expected:
            raise ValueError('Температура перед стартовой линией не совпадает с профилем слайсера. Автоматическая замена невозможна.')
        if any('bedTemperature' in profile for profile in resolved.values()):
            key = BED_KEYS.get(self.metadata.get('curr_bed_type'))
            if key is None:
                raise ValueError('Неизвестный тип стола в G-code. Оставьте температуру стола пустой или выберите поддерживаемую пластину в слайсере.')
            self.bed_baseline.update(vector(self.metadata, key))
            self.bed_baseline.update(vector(self.metadata, key + '_initial_layer'))
            self.bed_baseline.update(vector(self.metadata, 'first_layer_bed_temperature'))
        self.resolve(task)

    def mapping(self, task):
        table = task.get('extruder_map_table', [])
        if any(index >= len(table) or type(table[index]) is not int or table[index] not in range(4) or
               index >= len(self.nozzle) or index >= len(self.initial) for index in self.used):
            raise ValueError('Неизвестная карта головок U1 или неполные температуры слайсера.')
        return table

    def resolve(self, task):
        table = self.mapping(task)
        inventory = self.data['inventory']
        colors = {color['id']: color for color in self.data['library']['entries']}
        spools = {spool['id']: spool for spool in inventory['spools']}
        result = {}
        for head in {table[index] for index in self.used}:
            spool = spools.get(inventory['heads'][head])
            profile = {}
            if spool:
                color = colors.get(spool['colorId'], {})
                calibration = spool.get('calibration', {}) if inventory.get('individualCalibration') else color.get('calibration', {})
                for key, low, high in (('nozzleTemperature', 150, min(300, self.nozzle_max)), ('bedTemperature', 20, min(100, self.bed_max))):
                    source = spool if key in spool else color
                    if key in source:
                        profile[key] = numeric(source[key], low, high)
                if 'pressureAdvance' in calibration:
                    profile['pressureAdvance'] = numeric(calibration['pressureAdvance'], 0, 1)
                if profile and (spool['material'] != task['filament_type'][head] or
                                spool['hex'].lstrip('#').upper() != task['filament_color_rgba'][head][:6].upper() or
                                (color and (color['material'] != spool['material'] or color['hex'].upper() != spool['hex'].upper()))):
                    raise ValueError('Головка %d: привязанная катушка не совпадает с материалом/цветом принтера. Проверьте назначение катушки.' % (head + 1))
            result[head] = profile
        beds = {profile['bedTemperature'] for profile in result.values() if 'bedTemperature' in profile}
        if len(beds) > 1:
            raise ValueError('У используемых катушек разные температуры общего стола. Укажите одинаковую температуру или оставьте её пустой для слайсера.')
        return result

    def physical(self, logical, task, direct=False):
        if type(logical) is not int or logical < 0:
            raise ValueError('Неверный номер головки в G-code.')
        if direct:
            if logical not in range(4):
                raise ValueError('Неверный номер физической головки.')
            return logical
        table = self.mapping(task)
        if logical >= len(table) or table[logical] not in range(4):
            raise ValueError('Неизвестный номер головки в G-code.')
        return table[logical]

    def k_values(self, task, actual):
        result = {}
        for head, profile in self.resolve(task).items():
            # Stock U1 ignores ALL SET_PRESSURE_ADVANCE during printing when this
            # global preference is set, even for heads not selected for the test.
            fresh = task.get('flow_calibrate') is True
            if fresh:
                self.fresh_k.setdefault(head, actual[head])
            elif 'pressureAdvance' in profile:
                result[head] = profile['pressureAdvance']
        return result

    def rewrite(self, line, position, task, active):
        if not self.enabled or self.ended:
            return line
        body = command(line)
        if re.match(r'^(?:PRINT_END|INNER_PRINT_END|END_PRINT)(?:\s|$)', body, re.I):
            self.ended = True
            return line
        if position == self.prime_offset:
            self.printing = True
        code = body.split(None, 1)[0].upper() if body else ''
        if code not in ('M104', 'M109', 'M140', 'M190', 'SET_PRESSURE_ADVANCE'):
            return line
        profiles = self.resolve(task)
        if code == 'SET_PRESSURE_ADVANCE' and self.printing:
            match = re.search(r'(?:^|\s)EXTRUDER=(extruder[123]?)(?=\s|$)', body, re.I)
            if 'EXTRUDER=' in body.upper() and not match:
                return line
            head = (int(match.group(1)[8:] or 0) if match else active)
            value = self.fresh_k.get(head, profiles.get(head, {}).get('pressureAdvance'))
            if value is not None and re.search(r'(?:^|\s)ADVANCE=', body, re.I):
                return replace_number(line, 'ADVANCE', value, True)
            return line
        target = parameter(line, 'S')
        if target is None or target <= 0:
            return line
        if code in ('M140', 'M190'):
            values = {profile['bedTemperature'] for profile in profiles.values() if 'bedTemperature' in profile}
            if values and target in self.bed_baseline:
                return replace_number(line, 'S', next(iter(values)))
        elif self.printing:
            logical = parameter(line, 'T')
            head = active if logical is None else self.physical(int(logical), task, parameter(line, 'A', 1) == 0)
            baseline = {values[index] for index in self.used if self.mapping(task)[index] == head for values in (self.nozzle, self.initial)}
            value = profiles.get(head, {}).get('nozzleTemperature')
            if value is not None and target in baseline:
                return replace_number(line, 'S', value)
        return line


class U1FilamentProfiles:
    def __init__(self, config):
        self.printer = config.get_printer()
        self.data_file = config.get('data_file', '/userdata/u1-addons/filament-ui-data/current.json')
        self.plan = None
        self.status = {'version': 1, 'state': 'ready', 'message': '', 'heads': {}}
        self.pending = None
        self.printer.register_event_handler('klippy:ready', self.connect)

    def connect(self):
        self.vsd = self.printer.lookup_object('virtual_sdcard')
        self.gcode = self.printer.lookup_object('gcode')
        self.task = self.printer.lookup_object('print_task_config')
        self.toolhead = self.printer.lookup_object('toolhead')
        self.original_resume = self.vsd.do_resume
        self.original_process = self.vsd.process_gcode_line
        self.vsd.do_resume = self.resume
        self.vsd.process_gcode_line = self.process

    def get_status(self, eventtime=None):
        return copy.deepcopy(self.status)

    def resume(self):
        if self.vsd.work_timer is not None:
            return self.original_resume()
        if self.vsd.current_file is None:
            return self.original_resume()
        if self.vsd.file_position == 0:
            self.plan, self.pending = None, None
            try:
                if os.path.exists(os.path.join(os.path.dirname(self.data_file), 'transaction.json')):
                    raise ValueError('Восстановление базы дополнения ещё не завершено.')
                with open(self.data_file, encoding='utf-8') as source:
                    raw = json.load(source)
                if raw.get('format') != 'u1-filament-data' or raw.get('version') != 1:
                    raise ValueError('Неизвестная версия базы профилей.')
                config = self.printer.lookup_object('configfile').get_status(0)['settings']
                maximum = min(config[name]['max_temp'] for name in ('extruder', 'extruder1', 'extruder2', 'extruder3'))
                self.plan = PrintPlan(raw['data'], self.task.get_status(), self.vsd.current_file.name,
                                      maximum, config['heater_bed']['max_temp'])
                self.status = {'version': 1, 'state': 'prepared' if self.plan.enabled else 'ready', 'message': '',
                               'nativeCalibration': self.task.get_status().get('flow_calibrate') is True,
                               'heads': {str(head): value for head, value in self.plan.resolve(self.task.get_status()).items()} if self.plan.enabled else {}}
            except Exception as error:
                self.status = {'version': 1, 'state': 'error', 'message': str(error), 'heads': {}}
                raise self.printer.command_error('U1: ' + str(error))
        elif self.plan is None:
            self.status = {'version': 1, 'state': 'stock-recovery', 'message': 'Восстановление печати использует штатное сохранённое состояние U1.', 'heads': {}}
        return self.original_resume()

    def active_head(self):
        name = self.toolhead.get_extruder().get_name()
        return int(name[8:] or 0)

    def actual_k(self):
        return {head: self.printer.lookup_object('extruder' if head == 0 else 'extruder%d' % head).get_status(0)['pressure_advance'] for head in range(4)}

    def apply_k(self, task):
        for head, value in self.plan.k_values(task, self.actual_k()).items():
            name = 'extruder' if head == 0 else 'extruder%d' % head
            if abs(self.actual_k()[head] - value) > 0.0000001:
                self.gcode.run_script_from_command('SET_PRESSURE_ADVANCE EXTRUDER=%s ADVANCE=%.9g' % (name, value))
                if abs(self.actual_k()[head] - value) > 0.0000001:
                    raise ValueError('Не подтверждено применение K головки %d.' % (head + 1))

    def process(self, line):
        line = self.original_process(line)
        if self.plan is None or not self.plan.enabled or self.plan.ended:
            return line
        try:
            code = command(line)
            at_prime = self.vsd.file_position == self.plan.prime_offset
            interesting = at_prime or re.match(r'^(?:M104|M109|M140|M190|T\d+|SET_PRESSURE_ADVANCE|PRINT_END|INNER_PRINT_END|END_PRINT)(?:\s|$)', code, re.I)
            if not interesting:
                return line
            task = self.task.get_status()
            if at_prime or (self.plan.printing and re.match(r'^T\d+(?:\s|$)', code, re.I)):
                self.apply_k(task)
            result = self.plan.rewrite(line, self.vsd.file_position, task, self.active_head())
            self.status.update(state='active' if self.plan.printing and not self.plan.ended else ('finished' if self.plan.ended else 'prepared'),
                               nativeCalibration=task.get('flow_calibrate') is True,
                               heads={str(head): value for head, value in self.plan.resolve(task).items()})
            if result != line:
                self.gcode.respond_info('U1: ' + command(line) + ' → ' + command(result))
            return result
        except Exception as error:
            self.status.update(state='error', message=str(error))
            raise self.printer.command_error('U1: ' + str(error))


def load_config(config):
    return U1FilamentProfiles(config)
