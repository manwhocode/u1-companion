 def api(self,path):
  if path.startswith('/printer/objects/query'):return {'status':copy.deepcopy(self.status)}
  if path.startswith('/server/files/metadata'):return {**self.meta,'size':self.file.stat().st_size,'modified':self.file.stat().st_mtime}
