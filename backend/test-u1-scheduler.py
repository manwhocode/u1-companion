 def test_native_websocket_contract_without_real_connection(self):
  import types,sys
  sent=[]
  class Socket:
   async def write_message(self,value):sent.append(json.loads(value))
   async def read_message(self):return json.dumps({'id':1,'result':{'state':'success'}})
   def close(self):sent.append('closed')
  async def connect(*args,**kwargs):return Socket()
  module=types.ModuleType('tornado.websocket');module.websocket_connect=connect
  with patch.dict(sys.modules,{'tornado':types.ModuleType('tornado'),'tornado.websocket':module}):
   result=native_start('part.gcode',{'bed_level':1})
  self.assertEqual(result['state'],'success');self.assertEqual(sent[0]['method'],'server.files.start_local_print')
  self.assertEqual(sent[0]['params'],{'path':'part.gcode','options':{'bed_level':1}});self.assertEqual(sent[-1],'closed')

